"""
ULPF AI Parser Specification Repair.

Asks the local Qwen model to correct an invalid or inaccurate
parser specification using concrete evidence, field mismatches,
and expected values where available.
The LLM is an assistant, NOT the authority.
Never trust raw LLM output.
"""

from __future__ import annotations

import json
from typing import Any, Dict, List, Optional

from app.ai.ollama_client import generate_json
from app.ai.parser_generator import _normalize_parser_spec


REPAIR_PROMPT = """You are repairing a parser specification for ULPF.

The specification was generated by an AI model but failed schema validation, delimiter checks, or ground truth accuracy testing.

STRICT REPAIR RULES:
1. Correct the specification rather than inventing new data.
2. Fix ONLY the validation failures and field extraction mismatches.
3. Preserve correct fields, parser type, and valid delimiters.
4. Do NOT invent fields that do not exist in the raw logs.
5. Do NOT invent arbitrary values.
6. A timestamp field MUST have type "datetime".
7. Return ONLY valid JSON.
8. Do NOT write Python code.
9. Do NOT add executable code.

==================================================
ORIGINAL LOG SAMPLES:
==================================================
{log_samples}

==================================================
FLAWED / INACCURATE PARSER SPECIFICATION:
==================================================
{parser_spec}

==================================================
VALIDATION FAILURES:
==================================================
{errors}

==================================================
FIELD MISMATCHES:
==================================================
{field_mismatches}

==================================================
EXPECTED GROUND TRUTH VALUES:
==================================================
{expected_values}

Return the corrected parser specification with exactly:
format_name, parser_type, delimiter, fields, timestamp_field, key_value_separator, optional_fields, confidence
"""


def repair_parser_spec(
    log_samples: str,
    parser_spec: Dict[str, Any],
    errors: List[str],
    field_mismatches: Optional[List[Dict[str, Any]]] = None,
    expected_values: Optional[List[Dict[str, Any]]] = None,
    model: Optional[str] = None,
    timeout: Optional[float] = None,
) -> Dict[str, Any]:
    """
    Ask local Qwen to repair an invalid or inaccurate parser specification
    based on concrete validation failures, field mismatches, and expected values.
    """
    mismatches_text = (
        json.dumps(field_mismatches, indent=2)
        if field_mismatches
        else "None reported; check validation errors."
    )
    expected_text = (
        json.dumps(expected_values, indent=2)
        if expected_values
        else "None provided; align fields to raw log structure."
    )

    prompt = REPAIR_PROMPT.format(
        log_samples=log_samples,
        parser_spec=json.dumps(parser_spec, indent=2),
        errors="\n".join(errors) if errors else "None reported.",
        field_mismatches=mismatches_text,
        expected_values=expected_text,
    )

    repaired = generate_json(prompt, model=model, timeout=timeout)
    return _normalize_parser_spec(repaired)
